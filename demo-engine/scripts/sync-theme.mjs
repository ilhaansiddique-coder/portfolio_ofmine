// Copies a theme's source into ./theme so the engine renders it. The theme
// folder itself stays untouched (no preview cruft lands in it). Runs before
// dev/build. Pick the theme with THEME_SRC=/abs/path.
//
// A theme only has to implement the slots it cares about — the real engine
// falls back to its default theme for anything omitted. This preview imports
// theme pages statically, so a missing slot would be a hard build error. To
// keep that contract, any slot a theme leaves out is generated here as a small
// placeholder page, so the route still builds and says plainly that this theme
// doesn't ship that screen.

import { cpSync, rmSync, mkdirSync, existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = process.cwd();
const CANDIDATES = [
  process.env.THEME_SRC,
  resolve(ROOT, "..", "GBBD_Clone"),
  resolve(ROOT, "..", "cd-ecom-theme-template"),
].filter(Boolean);

const SRC = CANDIDATES.find((p) => existsSync(p));
const DEST = resolve(ROOT, "theme");

if (!SRC) {
  console.error(
    `\n[sync-theme] Could not find a theme source. Looked in:\n` +
      CANDIDATES.map((p) => `  ${p}`).join("\n") +
      "\n",
  );
  process.exit(1);
}

rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const item of ["pages", "chrome", "components", "images", "manifest.ts", "styles.css"]) {
  const from = resolve(SRC, item);
  if (existsSync(from)) cpSync(from, resolve(DEST, item), { recursive: true });
}

/**
 * Optional slots: the module the engine imports -> the exports it expects.
 * `default` is the page component; extra names are the engine's named imports.
 */
const OPTIONAL_SLOTS = {
  "pages/AccountPage.tsx": { title: "Account", exports: [] },
  "pages/BrandsPage.tsx": { title: "Brands", exports: ["BrandPage"] },
  "pages/TrackOrderPage.tsx": { title: "Track Order", exports: [] },
};

const placeholder = (title) => `// Auto-generated by scripts/sync-theme.mjs.
// This theme does not implement the "${title}" slot; in production the engine
// falls back to its default theme here.
import Link from "next/link";

function Missing() {
  return (
    <div className="tpl-page" style={{ maxWidth: 560 }}>
      <div className="tpl-panel" style={{ textAlign: "center", padding: "48px 24px" }}>
        <h1 style={{ fontSize: 22, fontWeight: 800, margin: "0 0 8px" }}>${title}</h1>
        <p style={{ color: "var(--tpl-muted)", margin: "0 0 24px" }}>
          This theme doesn&apos;t ship a ${title.toLowerCase()} screen — the storefront
          engine renders its default here.
        </p>
        <Link href="/" className="tpl-btn">Back to store</Link>
      </div>
    </div>
  );
}
`;

const generated = [];
for (const [file, { title, exports }] of Object.entries(OPTIONAL_SLOTS)) {
  const target = resolve(DEST, file);
  if (existsSync(target)) continue;

  const named = exports.map((n) => `export function ${n}() { return <Missing />; }`).join("\n");
  writeFileSync(target, `${placeholder(title)}\nexport default function Page() { return <Missing />; }\n${named}\n`);
  generated.push(file);
}

console.log(`[sync-theme] Theme copied into ./theme from:\n  ${SRC}`);
if (generated.length) {
  console.log(`[sync-theme] Slots this theme omits (placeholder generated): ${generated.join(", ")}`);
}
